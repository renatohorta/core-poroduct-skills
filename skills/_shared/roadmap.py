"""
roadmap.py — releases, iterations, epic planning and generated views (INIT-03 §7.5).

Releases and iterations are small files under `.context/roadmap/`
(`R<n>.md`, `R<n>-I<m>.md`). The roadmap and the board are generated views
(`docs/06-roadmap.md`, `docs/06-board.md`), never hand-edited. The curated
`docs/06-kanban.md` is never touched. `cards` is imported lazily (cycle).

Pure standard library.
"""
from __future__ import annotations

import re
from datetime import datetime
from pathlib import Path

from _shared import context, frontmatter
from _shared.discipline import fail
from _shared.rup import PHASES

HEADER = "> Generated by rup-backlog — do not edit."
ROADMAP_VIEW = "06-roadmap.md"
BOARD_VIEW = "06-board.md"
_RELEASE = re.compile(r"^R(\d+)$")
_ITERATION = re.compile(r"^R(\d+)-I(\d+)$")


def _dir(context_dir) -> Path:
    return Path(context_dir) / "roadmap"


def _load(context_dir, pattern) -> list:
    """[(numbers, meta, path)] of the roadmap files matching `pattern`, numerically sorted."""
    found = []
    folder = _dir(context_dir)
    for path in folder.glob("*.md") if folder.is_dir() else []:
        m = pattern.match(path.stem)
        if m:
            meta, _ = frontmatter.parse(path.read_text(encoding="utf-8"))
            meta.setdefault("id", path.stem)
            found.append((tuple(int(n) for n in m.groups()), meta, path))
    return sorted(found, key=lambda t: t[0])


def _write(context_dir, doc_id: str, meta: dict, heading: str, what: str) -> None:
    path = _dir(context_dir) / f"{doc_id}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(frontmatter.dump(meta, f"# {doc_id} — {heading}\n"), encoding="utf-8")
    context.append_event(context_dir, skill="rup-backlog", what=what)


def _line(label: str, value: str) -> str:
    from _shared import cards
    value = (value or "").strip()
    cards._check_line(label, value)
    return value


def new_release(context_dir, title, *, milestone="", goal="", target_date="") -> str:
    context.ensure_writable(context_dir)
    title = _line("title", title)
    if not title:
        fail("the release title is empty")
    milestone, goal, target_date = (_line("milestone", milestone), _line("goal", goal),
                                    _line("target_date", target_date))
    if milestone and milestone not in context.PHASE_MILESTONES.values():
        fail(f"unknown milestone {milestone!r} (valid: "
             + "; ".join(context.PHASE_MILESTONES.values()) + ")")
    n = max((nums[0] for nums, _, _ in _load(context_dir, _RELEASE)), default=0) + 1
    rid = f"R{n}"
    meta = {"id": rid, "title": title, "milestone": milestone, "goal": goal,
            "target_date": target_date}
    _write(context_dir, rid, meta, title, f"created release {rid}")
    regenerate_views(context_dir)
    return rid


def new_iteration(context_dir, release_id, phase, goal, *, start="", end="") -> str:
    context.ensure_writable(context_dir)
    if not any(m["id"] == release_id for _, m, _ in _load(context_dir, _RELEASE)):
        fail(f"unknown release {release_id}")
    if phase not in PHASES:
        fail(f"unknown phase {phase!r} (valid: {', '.join(PHASES)})")
    goal, start, end = _line("goal", goal), _line("start", start), _line("end", end)
    rel = int(release_id[1:])
    n = max((nums[1] for nums, _, _ in _load(context_dir, _ITERATION) if nums[0] == rel),
            default=0) + 1
    iid = f"{release_id}-I{n}"
    meta = {"id": iid, "release": release_id, "phase": phase, "goal": goal,
            "start": start, "end": end}
    _write(context_dir, iid, meta, f"{phase} iteration {n}", f"created iteration {iid}")
    regenerate_views(context_dir)
    return iid


def plan_epic(context_dir, epic_id, iteration_id):
    from _shared import cards
    context.ensure_writable(context_dir)
    epic = cards.get(context_dir, epic_id)
    if epic.type != "epic":
        fail(f"{epic_id} is a {epic.type}; only an epic can be planned into an iteration")
    its = {m["id"]: m for _, m, _ in _load(context_dir, _ITERATION)}
    if iteration_id not in its:
        fail(f"unknown iteration {iteration_id}")
    epic.meta["release"] = str(its[iteration_id].get("release", ""))
    epic.meta["iteration"] = iteration_id
    cards.add_history(epic, f"planned into {iteration_id}")  # persists the meta too
    context.append_event(context_dir, skill="rup-backlog",
                         what=f"planned {epic_id} into {iteration_id}")
    regenerate_views(context_dir)
    return epic


def _epic_line(epic, stories) -> str:
    mine = [s for s in stories if s.meta.get("parent") == epic.id]
    done = sum(1 for s in mine if s.status == "7-done")
    return f"- {epic.id} {epic.title} — {done}/{len(mine)} stories done ({epic.status})"


def render_roadmap(context_dir) -> str:
    from _shared import cards
    allc = list(cards.load_all(context_dir).values())
    epics = sorted((c for c in allc if c.type == "epic"), key=lambda c: c.id)
    stories = [c for c in allc if c.type == "story"]
    iterations = _load(context_dir, _ITERATION)
    known = {m["id"] for _, m, _ in iterations}
    out = [HEADER, "", "# Roadmap", ""]
    for nums, rel, _ in _load(context_dir, _RELEASE):
        title = f"## {rel['id']} — {rel.get('title', '')}"
        out += [title, ""]
        if rel.get("milestone"):
            out.append(f"Milestone: {rel['milestone']}")
        if rel.get("goal"):
            out.append(f"Goal: {rel['goal']}")
        if rel.get("target_date"):
            out.append(f"Target date: {rel['target_date']}")
        out.append("")
        for _, it, _ in (t for t in iterations if t[0][0] == nums[0]):
            out += [f"### {it['id']} — {it.get('phase', '')}", ""]
            if it.get("goal"):
                out += [f"Goal: {it['goal']}", ""]
            planned = [e for e in epics if e.meta.get("iteration") == it["id"]]
            out += [_epic_line(e, stories) for e in planned] or ["_No epics planned._"]
            out.append("")
    out += ["## Unplanned epics", ""]
    loose = [e for e in epics if e.meta.get("iteration") not in known]
    for e in loose:
        note = f" (unknown iteration {e.meta['iteration']})" if e.meta.get("iteration") else ""
        out.append(_epic_line(e, stories) + note)
    if not loose:
        out.append("_None._")
    return "\n".join(out) + "\n"


def render_board(context_dir) -> str:
    from _shared import cards
    allc = cards.load_all(context_dir).values()
    out = [HEADER, "", "# Board", ""]
    for column in cards.COLUMNS:
        out += [f"## {column}", ""]
        rows = sorted((c for c in allc if c.status == column), key=lambda c: c.id)
        out += [f"- {c.id} [{c.type}] {c.title}" for c in rows] or ["_Empty._"]
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def regenerate_views(context_dir) -> list:
    """Write `docs/06-roadmap.md` and `docs/06-board.md` (nothing else)."""
    context.ensure_writable(context_dir)
    docs = Path(context_dir) / "docs"
    docs.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in ((ROADMAP_VIEW, render_roadmap(context_dir)),
                       (BOARD_VIEW, render_board(context_dir))):
        (docs / name).write_text(text, encoding="utf-8")
        written.append(docs / name)
    return written
