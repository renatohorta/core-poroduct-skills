"""Roadmap: releases, iterations, planning and the generated views."""
import pytest

from conftest import EXIT_NEEDS_CONSENT, EXIT_OK, EXIT_USAGE, authorize
from test_cards import EPIC, STORY, ctx  # noqa: F401  (ctx fixture)

from _shared import cards, context, roadmap

HEADER = "> Generated by rup-backlog — do not edit."


def read(ctx, name):
    return (ctx / "docs" / name).read_text(encoding="utf-8")


def test_release_and_iteration_ids(ctx):
    assert roadmap.new_release(ctx, "MVP", milestone="Lifecycle Architecture (LCA)") == "R1"
    assert roadmap.new_release(ctx, "Scale") == "R2"
    assert roadmap.new_iteration(ctx, "R1", "Elaboration", "Core") == "R1-I1"
    assert roadmap.new_iteration(ctx, "R1", "Construction", "Build") == "R1-I2"
    assert roadmap.new_iteration(ctx, "R2", "Inception", "Start") == "R2-I1"
    with pytest.raises(SystemExit) as e:
        roadmap.new_iteration(ctx, "R9", "Inception", "x")
    assert e.value.code == EXIT_USAGE
    with pytest.raises(SystemExit) as e:
        roadmap.new_iteration(ctx, "R1", "Nope", "x")
    assert e.value.code == EXIT_USAGE
    with pytest.raises(SystemExit) as e:
        roadmap.new_release(ctx, "Bad", milestone="whatever")
    assert e.value.code == EXIT_USAGE


def test_numeric_ordering_past_nine(ctx):
    for i in range(10):
        roadmap.new_release(ctx, f"Rel {i}")
    assert roadmap.new_release(ctx, "Eleventh") == "R11"
    text = roadmap.render_roadmap(ctx)
    assert text.index("## R2 ") < text.index("## R10 ")


def test_plan_epic_sets_iteration_and_release(ctx):
    cards.create(ctx, "epic", "Booking", EPIC)
    roadmap.new_release(ctx, "MVP")
    roadmap.new_iteration(ctx, "R1", "Elaboration", "Core")
    epic = roadmap.plan_epic(ctx, "EP-001", "R1-I1")
    assert epic.meta["iteration"] == "R1-I1" and epic.meta["release"] == "R1"
    again = cards.get(ctx, "EP-001")
    assert again.meta["iteration"] == "R1-I1"
    assert again.body.rstrip().splitlines()[-1].endswith("planned into R1-I1")
    with pytest.raises(SystemExit) as e:
        roadmap.plan_epic(ctx, "EP-001", "R1-I9")
    assert e.value.code == EXIT_USAGE
    cards.create(ctx, "story", "Book", STORY, parent="EP-001")
    with pytest.raises(SystemExit) as e:
        roadmap.plan_epic(ctx, "ST-001", "R1-I1")
    assert e.value.code == EXIT_USAGE


def test_roadmap_shows_progress_and_unplanned(ctx):
    cards.create(ctx, "epic", "Booking", EPIC)
    cards.create(ctx, "epic", "Billing", EPIC)
    cards.create(ctx, "story", "A", STORY, parent="EP-001")
    cards.create(ctx, "story", "B", STORY, parent="EP-001")
    roadmap.new_release(ctx, "MVP", goal="First cut")
    roadmap.new_iteration(ctx, "R1", "Elaboration", "Core")
    roadmap.plan_epic(ctx, "EP-001", "R1-I1")
    cards.move(ctx, "ST-001", "7-done", "done")
    text = read(ctx, "06-roadmap.md")
    assert text.startswith(HEADER)
    assert "EP-001 Booking — 1/2 stories done (3-doing)" in text
    assert "Goal: First cut" in text and "R1-I1 — Elaboration" in text
    unplanned = text.split("## Unplanned epics")[1]
    assert "EP-002 Billing — 0/0 stories done (1-backlog)" in unplanned
    # an epic pointing at a vanished iteration is unplanned, with a note
    (ctx / "roadmap" / "R1-I1.md").unlink()
    assert "EP-001 Booking" in roadmap.render_roadmap(ctx).split("## Unplanned epics")[1]
    assert "(unknown iteration R1-I1)" in roadmap.render_roadmap(ctx)


def test_board_lists_every_column(ctx):
    cards.create(ctx, "epic", "Booking", EPIC)
    text = roadmap.render_board(ctx)
    assert text.startswith(HEADER)
    for column in cards.COLUMNS:
        assert f"## {column}" in text
    assert "- EP-001 [epic] Booking" in text.split("## 1-backlog")[1].split("## 2-todo")[0]


def test_views_regenerated_after_move(ctx):
    cards.create(ctx, "epic", "Booking", EPIC)
    assert "## 1-backlog\n\n- EP-001 [epic] Booking" in read(ctx, "06-board.md")
    cards.move(ctx, "EP-001", "2-todo", "ready")
    board = read(ctx, "06-board.md")
    assert "## 2-todo\n\n- EP-001 [epic] Booking" in board
    cards.set_section(cards.get(ctx, "EP-001"), "Scope", "Changed")
    assert (ctx / "docs" / "06-roadmap.md").is_file()


def test_06_kanban_never_touched(ctx):
    (ctx / "docs").mkdir(parents=True, exist_ok=True)
    kanban = ctx / "docs" / "06-kanban.md"
    kanban.write_bytes(b"# curated\r\nkeep me\n")
    cards.create(ctx, "epic", "Booking", EPIC)
    cards.move(ctx, "EP-001", "2-todo", "ready")
    roadmap.new_release(ctx, "MVP")
    roadmap.regenerate_views(ctx)
    assert kanban.read_bytes() == b"# curated\r\nkeep me\n"


def test_writers_need_consent(tmp_path):
    bare = tmp_path / ".context"
    bare.mkdir()
    for call in (lambda: roadmap.new_release(bare, "x"),
                 lambda: roadmap.regenerate_views(bare)):
        with pytest.raises(SystemExit) as e:
            call()
        assert e.value.code == EXIT_NEEDS_CONSENT
    assert not (bare / "roadmap").exists() and not (bare / "docs").exists()


def test_cli_roadmap_flow(ctx, clean_env, python_cmd):
    from test_context_persistence import run_skill
    env = {**clean_env, "RUP_CONTEXT_DIR": str(ctx)}

    def run(*args):
        return run_skill("rup-backlog", list(args), env, python_cmd)

    cards.create(ctx, "epic", "Booking", EPIC)
    r = run("--release-new", "--title", "MVP")
    assert r.returncode == EXIT_OK and r.stdout.strip() == "R1"
    r = run("--iteration-new", "--release", "R1", "--phase", "Construction", "--goal", "Build")
    assert r.stdout.strip() == "R1-I1"
    assert run("--plan", "EP-001", "--iteration", "R1-I1").returncode == EXIT_OK
    assert run("--plan", "EP-001", "--iteration", "R1-I7").returncode == EXIT_USAGE
    r = run("--roadmap")
    assert r.returncode == EXIT_OK and "06-roadmap.md" in r.stdout
    assert "EP-001 Booking" in read(ctx, "06-roadmap.md")


def test_regenerate_never_overwrites_a_hand_written_view(ctx, capsys):
    (ctx / "docs").mkdir(exist_ok=True)
    mine = ctx / "docs" / "06-roadmap.md"
    mine.write_text("# My own roadmap\n", encoding="utf-8")
    cards.create(ctx, "epic", "A", EPIC)
    cards.move(ctx, "EP-001", "2-todo", "ready")
    assert mine.read_text(encoding="utf-8") == "# My own roadmap\n"
    err = capsys.readouterr().err
    assert "06-roadmap.md exists and is not generated by rup-backlog — not overwritten" in err
    assert (ctx / "docs" / "06-board.md").read_text(encoding="utf-8").startswith(HEADER)
    assert roadmap.foreign_views(ctx) == [mine]
